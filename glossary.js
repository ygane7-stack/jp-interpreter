// 화면 힌트·Soniox 문맥에 쓰는 전체 짝 목록
export function allPairs(buildingId) {
  const b = BUILDINGS.find((x) => x.id === buildingId);
  const pairs = [...ARCHITECTS, ...TERMS];
  for (const x of BUILDINGS) pairs.push([x.ja.replace(/（.*?）/g, ""), x.ko.replace(/\(.*?\)/g, "")]);
  if (b) pairs.push(...b.terms);
  else for (const x of BUILDINGS) pairs.push(...x.terms);
  // 같은 일본어는 하나만, 긴 것 먼저(힌트 찾기에서 긴 말이 먼저 걸리게)
  const seen = new Set();
  return pairs.filter(([ja]) => (seen.has(ja) ? false : seen.add(ja))).sort((a, b2) => b2[0].length - a[0].length);
}

