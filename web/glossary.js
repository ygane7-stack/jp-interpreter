// 화면 힌트·Soniox 문맥에 쓰는 짝 목록 — 중요한 것 먼저(고른 건물 용어 → 중국어 → 건축가 → 일정 건물 → 일반 용어 → 나머지 건물)
export function allPairs(buildingId, lang = "ja") {
  const b = BUILDINGS.find((x) => x.id === buildingId);
  const name = (x) => [x.ja.replace(/（.*?）/g, ""), x.ko.replace(/\(.*?\)/g, "")];
  const pairs = [];
  if (b) pairs.push(...b.terms, name(b));
  if (lang !== "ja") pairs.push(...ZH_TERMS);
  pairs.push(...ARCHITECTS);
  for (const x of BUILDINGS.filter((x) => x.day)) pairs.push(name(x));
  pairs.push(...TERMS);
  for (const x of BUILDINGS.filter((x) => x.day)) pairs.push(...x.terms);
  for (const x of BUILDINGS.filter((x) => !x.day)) pairs.push(name(x), ...x.terms);
  const seen = new Set();
  return pairs.filter(([ja]) => (seen.has(ja) ? false : seen.add(ja)));
}

// 내가 말하기(한국어 → 일본어)용 Soniox 문맥: 같은 용어집을 거꾸로(한→일) 넘긴다
export function talkContext(buildingId) {
  const b = BUILDINGS.find((x) => x.id === buildingId);
  const general = [
    { key: "domain", value: "韓国人の建築好きの旅行者が、建築ガイド・学芸員・地元の人に話しかける" },
    { key: "style", value: "丁寧な日本語（です・ます）" },
  ];
  if (b) general.push({ key: "building", value: b.ja }, { key: "architect", value: b.arch });
  const ctx = { general, text: b ? `見学中の建物: ${b.ja}（${b.arch}）` : "日本の現代建築を巡る旅行", terms: [], translation_terms: [] };
  let size = JSON.stringify(ctx).length;
  const seen = new Set();
  for (const [ja, ko] of allPairs(buildingId, "ja")) {
    const src = ko.replace(/\(.*?\)/g, "").trim();
    if (!src || seen.has(src) || !/[가-힣]/.test(src)) continue;
    seen.add(src);
    const tt = { source: src, target: ja };
    const add = src.length + 3 + JSON.stringify(tt).length + 1;
    if (size + add > 5500) break;
    ctx.terms.push(src); ctx.translation_terms.push(tt); size += add;
  }
  return ctx;
}

// Soniox context 만들기(8000 토큰 안쪽)
export function sonioxContext(buildingId, lang = "ja") {
  const b = BUILDINGS.find((x) => x.id === buildingId);
  const pairs = allPairs(buildingId, lang);
  const general = [
    { key: "domain", value: lang === "ja" ? "建築ガイドツアー（日本の現代建築・建築史）" : "建築講演（中国語の講演と日本語の通訳）" },
    { key: "speaker", value: "建築ガイド・学芸員の解説" },
    { key: "listener", value: "韓国人の建築好きの旅行者" },
  ];
  let text = lang === "ja"
    ? "日本の現代建築を巡る見学ツアーで、ガイドが建物・建築家・構造・素材を説明している。"
    : "中国の建築家 王澍（ワン・シュウ）と陸文宇が中国語で講演し、日本語の通訳が入る。建築、園林、伝統的な材料の再利用について話す。";
  if (b) {
    general.push({ key: "building", value: b.ja });
    general.push({ key: "architect", value: b.arch });
    general.push({ key: "place", value: b.place });
    text += ` 現在見学中: ${b.ja}（設計: ${b.arch}、${b.place}）。${b.note}`;
  }
  const ctx = { general, text, terms: [], translation_terms: [] };
  // 문맥은 최대 약 8000토큰 → 넉넉히 글자 수 5500 안에서 중요한 것부터 담는다
  let size = JSON.stringify(ctx).length;
  for (const [ja, ko] of pairs) {
    const tt = { source: ja, target: ko.replace(/\(.*?\)/g, "").trim() };
    const add = ja.length + 3 + JSON.stringify(tt).length + 1;
    if (size + add > 5500) break;
    if (/[぀-ヿ一-鿿]/.test(ja)) ctx.terms.push(ja);
    ctx.translation_terms.push(tt);
    size += add;
  }
  return ctx;
}
